"""Traefik routing for a node, rendered from its domain by ``pluginlake setup``.

Every application is published on its own subdomain behind oauth2-proxy forward auth and needs the identity provider
role with the same name as the application. Only the identity provider and the oauth2-proxy endpoints are public.
"""

import json

APPLICATIONS = {
    "api": "http://pluginlake:8000",
    "console": "http://dashboard-datastation:8501",
    "dagster": "http://dagster-webserver:3000",
    "marquez": "http://marquez-web:3000",
    "prometheus": "http://prometheus:9090",
}
BROWSER_APPLICATIONS = tuple(name for name in APPLICATIONS if name != "api")
ROOT_REDIRECT_TARGET = "console"
OAUTH2_PROXY_URL = "http://oauth2-proxy:4180"
IDENTITY_HEADERS = [
    "X-Auth-Request-User",
    "X-Auth-Request-Email",
    "X-Auth-Request-Groups",
    "X-Auth-Request-Access-Token",
]
HEADER = "# Generated by `pluginlake setup` from [node] domain in pluginlake.toml. Do not edit.\n"


def _host(domain: str, subdomain: str | None = None) -> str:
    return f"Host(`{subdomain}.{domain}`)" if subdomain else f"Host(`{domain}`)"


def _routers(domain: str) -> dict:
    auth = _host(domain, "auth")
    all_hosts = " || ".join([_host(domain), *(_host(domain, name) for name in APPLICATIONS)])
    routers = {
        "zitadel-login": {
            "entryPoints": ["websecure"],
            "rule": f"{auth} && PathPrefix(`/ui/v2/login`)",
            "service": "zitadel-login",
            "priority": 250,
        },
        "zitadel-root": {
            "entryPoints": ["websecure"],
            "rule": f"{auth} && Path(`/`)",
            "service": "zitadel-login",
            "middlewares": ["zitadel-root-rewrite"],
            "priority": 400,
        },
        "zitadel": {"entryPoints": ["websecure"], "rule": auth, "service": "zitadel-api", "priority": 100},
        "oauth2-proxy": {
            "entryPoints": ["websecure"],
            "rule": f"({all_hosts}) && PathPrefix(`/oauth2/`)",
            "service": "oauth2-proxy",
            "priority": 300,
        },
        "root": {
            "entryPoints": ["websecure"],
            "rule": _host(domain),
            "service": ROOT_REDIRECT_TARGET,
            "middlewares": ["root-redirect"],
        },
    }
    for name in APPLICATIONS:
        guards = ["sso-starting", "sso-errors", "sso-forbidden"] if name in BROWSER_APPLICATIONS else ["sso-errors"]
        routers[name] = {
            "entryPoints": ["websecure"],
            "rule": _host(domain, name),
            "service": name,
            "middlewares": [*guards, f"sso-auth-{name}"],
        }
    return routers


def _services() -> dict:
    urls = {
        "zitadel-api": "h2c://zitadel-api:8080",
        "zitadel-login": "http://zitadel-login:3000",
        "oauth2-proxy": OAUTH2_PROXY_URL,
        "starting-page": "http://starting-page:8080",
        **APPLICATIONS,
    }
    return {name: {"loadBalancer": {"servers": [{"url": url}]}} for name, url in urls.items()}


def _forward_auth(application: str) -> dict:
    return {
        "forwardAuth": {
            "address": f"{OAUTH2_PROXY_URL}/oauth2/auth?allowed_groups={application}",
            "trustForwardHeader": True,
            "maxResponseBodySize": 65536,
            "authResponseHeaders": IDENTITY_HEADERS,
        }
    }


def _middlewares(domain: str) -> dict:
    end_session = f"https%3A%2F%2Fauth.{domain}%2Foidc%2Fv1%2Fend_session"
    return {
        "root-redirect": {
            "redirectRegex": {"regex": "^https://[^/]+/.*", "replacement": f"https://{ROOT_REDIRECT_TARGET}.{domain}/"}
        },
        "zitadel-root-rewrite": {"replacePath": {"path": "/ui/v2/login/"}},
        **{f"sso-auth-{name}": _forward_auth(name) for name in APPLICATIONS},
        "sso-errors": {
            "errors": {
                "status": ["401"],
                "statusRewrites": {"401": 302},
                "service": "oauth2-proxy",
                # Traefik fills in the escaped path, so oauth2-proxy returns the user to the page they asked for.
                "query": "/oauth2/sign_in?rd={url}",
            }
        },
        # Traefik is reachable before oauth2-proxy and the applications are, so a server error shows a waiting page.
        "sso-starting": {"errors": {"status": ["500-599"], "service": "starting-page", "query": "/"}},
        # A signed-in user without the role is signed out, also at the identity provider.
        "sso-forbidden": {
            "errors": {
                "status": ["403"],
                "statusRewrites": {"403": 302},
                "service": "oauth2-proxy",
                "query": f"/oauth2/sign_out?rd={end_session}",
            }
        },
    }


def render_routes(domain: str) -> str:
    """Render the Traefik dynamic configuration for a node.

    Args:
        domain: Base domain of the node. Applications live on subdomains and the identity provider on ``auth.``.

    Returns:
        The routers, services and middlewares as a file-provider document. JSON is valid YAML.
    """
    http = {"routers": _routers(domain), "services": _services(), "middlewares": _middlewares(domain)}
    return HEADER + json.dumps({"http": http}, indent=2) + "\n"
